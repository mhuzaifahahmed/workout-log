// Runs at build time (locally via `npm run build`, or automatically on Cloudflare Pages).
// Writes config.js from environment variables so no secrets are committed to the repo.
const fs = require("fs");
const path = require("path");

function loadDotEnv() {
  const envPath = path.join(__dirname, ".env");
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const idx = trimmed.indexOf("=");
    if (idx === -1) continue;
    const key = trimmed.slice(0, idx).trim();
    const val = trimmed.slice(idx + 1).trim().replace(/^["']|["']$/g, "");
    if (!(key in process.env)) process.env[key] = val;
  }
}

loadDotEnv();

const url = process.env.SUPABASE_URL || "";
const key = process.env.SUPABASE_ANON_KEY || "";

const content = `// Auto-generated by build-config.js from environment variables — do not edit by hand.
// Local dev: edit .env (see .env.example). Production: Cloudflare Pages → Settings → Environment variables.
const SUPABASE_URL = "${url}";
const SUPABASE_ANON_KEY = "${key}";
`;

fs.writeFileSync(path.join(__dirname, "config.js"), content);
console.log(`config.js generated — SUPABASE_URL ${url ? "set" : "EMPTY"}, SUPABASE_ANON_KEY ${key ? "set" : "EMPTY"}`);
